# 🧬 HLA Typing Analysis (Immunogenomics)

## Objective
To analyze Human Leukocyte Antigen (HLA) alleles and understand immunogenetic variation in disease.

---

## 🔬 Workflow
- Input: Sequencing data (FASTQ)
- Performed HLA allele prediction using OptiType
- Interpreted allele distribution and immune relevance

---

## 🛠 Tools Used
- OptiType
- Python-based bioinformatics tools

---

## 📊 Expected Output
- Predicted HLA alleles (e.g., HLA-A, HLA-B, HLA-C)
- Allele frequency and distribution

---

## 💡 Biological Insight
HLA genes play a crucial role in antigen presentation and immune response.  
Variation in HLA alleles is associated with autoimmune diseases like Rheumatoid Arthritis.

---

## 📌 Note
This analysis is part of a multi-omics framework integrating transcriptomics, epigenomics, and proteomics.
